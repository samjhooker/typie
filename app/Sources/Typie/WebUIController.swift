/// Which flow the web view is hosting.
enum WebRoute: String {
    case onboarding
    case app
}

/// Hosts typie's web UI (built from app/webui, bundled at
/// Resources/webui/) inside a WKWebView, and bridges state both ways.
///
/// Swift -> JS: full state snapshots pushed as JSON into
/// `window.__typie.push(...)` whenever any store changes (coalesced).
/// JS -> Swift: actions via `webkit.messageHandlers.typie.postMessage`.
/// Standalone message-handler object: must be registered on the
/// WKWebViewConfiguration *before* the WKWebView is created (WebKit
/// ignores configuration changes afterwards), so it can't be the
/// controller itself — that would need self before super.init.
private final class ScriptBridge: NSObject, WKScriptMessageHandler {
    var onMessage: (([String: Any]) -> Void)?

    nonisolated func userContentController(
        _ userContentController: WKUserContentController,
        didReceive message: WKScriptMessage
    ) {
        guard message.name == "typie" else { return }
        MainActor.assumeIsolated {
            onMessage?(message.body as? [String: Any] ?? [:])
        }
    }
}

/// Serves the bundled web UI over typie:// so ES modules, fetch() and
/// friends work (they refuse file:// URLs). Paths map 1:1 into the
/// WebResources/webui/ folder inside the resource bundle.
private final class SchemeHandler: NSObject, WKURLSchemeHandler {
    private static let mimeTypes = [
        "html": "text/html", "js": "text/javascript", "mjs": "text/javascript",
        "css": "text/css", "json": "application/json", "svg": "image/svg+xml",
        "ttf": "font/ttf", "otf": "font/otf", "woff": "font/woff",
        "woff2": "font/woff2", "png": "image/png", "jpg": "image/jpeg",
        "jpeg": "image/jpeg", "gif": "image/gif", "webp": "image/webp",
        "ico": "image/x-icon", "wasm": "application/wasm", "map": "application/json",
        "wav": "audio/wav", "mp3": "audio/mpeg", "m4a": "audio/mp4",
        "mp4": "video/mp4", "aac": "audio/aac", "caf": "audio/caf", "flac": "audio/flac",
    ]

    func webView(_ webView: WKWebView, start task: WKURLSchemeTask) {
        guard let url = task.request.url,
              let root = WebUIController.webUIRoot
        else { return fail(task) }

        // strip query/fragment, resolve within the bundle folder only
        var components = URLComponents(url: url, resolvingAgainstBaseURL: false)!
        components.query = nil
        components.fragment = nil
        var relPath = percentDecode(components.url?.path ?? "/index.html")
        // URL paths always carry a leading "/" — strip it or prefix checks below
        // silently never match (this exact bug muted all transcript audio once)
        while relPath.hasPrefix("/") { relPath.removeFirst() }
        if relPath.isEmpty { relPath = "index.html" }

        // transcript audio lives OUTSIDE the bundle, in the data dir —
        // served so the web UI can scrub recordings word-by-word
        if relPath.hasPrefix("transcript-audio/") {
            return serveTranscriptAudio(task, url: url, name: String(relPath.dropFirst("transcript-audio/".count)))
        }

        let fileURL = root.appendingPathComponent(relPath)

        guard fileURL.standardizedFileURL.path.hasPrefix(root.standardizedFileURL.path),
            let data = try? Data(contentsOf: fileURL)
        else { return fail(task) }

        respond(task, url: url, data: data, ext: fileURL.pathExtension.lowercased(), rangeHeader: task.request.value(forHTTPHeaderField: "Range"))
    }

    /// Serve one stashed recording from <support>/transcripts/audio/<name>.
    /// Names are UUID.ext generated by TranscriptStore, but stay defensive:
    /// anything containing a path separator is rejected outright.
    private func serveTranscriptAudio(_ task: WKURLSchemeTask, url: URL, name: String) {
        guard !name.isEmpty, !name.contains("/"), !name.contains("..") else { return fail(task) }
        let fileURL = AppPaths.supportDir
            .appendingPathComponent("transcripts/audio", isDirectory: true)
            .appendingPathComponent(name)
        guard let data = try? Data(contentsOf: fileURL) else { return fail(task) }
        respond(task, url: url, data: data, ext: fileURL.pathExtension.lowercased(), rangeHeader: task.request.value(forHTTPHeaderField: "Range"))
    }

    /// Full 200 or byte-range 206 response (media elements seek via ranges).
    private func respond(_ task: WKURLSchemeTask, url: URL, data: Data, ext: String, rangeHeader: String?) {
        let mime = Self.mimeTypes[ext] ?? "application/octet-stream"

        if let header = rangeHeader, header.hasPrefix("bytes="),
           let range = Self.parseRange(header, total: data.count) {
            let slice = data.subdata(in: range.offset..<(range.offset + range.length))
            let response = HTTPURLResponse(
                url: url, statusCode: 206, httpVersion: nil,
                headerFields: [
                    "Content-Type": mime,
                    "Content-Length": String(range.length),
                    "Content-Range": "bytes \(range.offset)-\(range.offset + range.length - 1)/\(data.count)",
                    "Accept-Ranges": "bytes",
                    "Cache-Control": "no-store",
                ]
            )!
            task.didReceive(response)
            task.didReceive(slice)
            task.didFinish()
            return
        }

        // NB: no-store is load-bearing — without cache headers WebKit
        // heuristically caches typie:// responses, and a stale index.html
        // keeps serving an old UI bundle across app updates.
        let response = HTTPURLResponse(
            url: url, statusCode: 200, httpVersion: nil,
            headerFields: [
                "Content-Type": mime,
                "Content-Length": String(data.count),
                "Cache-Control": "no-store",
                "Content-Encoding": "identity",
            ]
        )!
        task.didReceive(response)
        task.didReceive(data)
        task.didFinish()
    }

    /// "bytes=a-b" / "bytes=a-" → (offset, length) clamped to the file
    private static func parseRange(_ header: String, total: Int) -> (offset: Int, length: Int)? {
        guard total > 0 else { return nil }
        let spec = header.dropFirst("bytes=".count).split(separator: "-")
        guard let first = spec.first, let offset = Int(first), offset < total else { return nil }
        let end = spec.count > 1 ? min(Int(spec[1]) ?? total - 1, total - 1) : total - 1
        guard end >= offset else { return nil }
        return (offset, end - offset + 1)
    }

    func webView(_ webView: WKWebView, stop task: WKURLSchemeTask) {}

    private func percentDecode(_ path: String) -> String {
        path.removingPercentEncoding ?? path
    }

    private func fail(_ task: WKURLSchemeTask) {
        AppLog.event("webui scheme: missing resource \(task.request.url?.path ?? "?")")
        task.didFailWithError(NSError(domain: "app.typie.webui", code: 404))
    }
}

@MainActor
final class WebUIController: NSObject, NSWindowDelegate {
    let window: NSWindow

    /// window closed by the user (or code)
    var onWillClose: (() -> Void)?
    /// explicit "done" from the onboarding flow
    var onComplete: (() -> Void)?
    /// became the key window (used to route transcripts to the practice box)
    var onBecomeKey: (() -> Void)?
    var onResignKey: (() -> Void)?

    private let route: WebRoute
    private let webView: WKWebView
    private let bridge = ScriptBridge()

    private var pageReady = false
    private var pendingPane: String?
    private var cancellables = Set<AnyCancellable>()
    private var permissionPoller: Timer?

    // hotkey capture ("click the keycap, press a modifier")
    private var captureMonitor: Any?
    private(set) var capturingHotkey = false

    // model-download ETA bookkeeping (mirrors the old onboarding math)
    private static var downloadStart: Date?

    private static let iso8601: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime]
        return f
    }()

    init(route: WebRoute, title: String, size: NSSize) {
        self.route = route

        // register the bridge BEFORE the web view exists — mandatory,
        // later additions to the config are ignored by WebKit
        let config = WKWebViewConfiguration()
        config.userContentController.add(bridge, name: "typie")
        config.setURLSchemeHandler(SchemeHandler(), forURLScheme: "typie")

        let view = WKWebView(frame: .zero, configuration: config)
        // no white flash before the first paint of the cream page
        view.setValue(false, forKey: "drawsBackground")
        view.underPageBackgroundColor = NSColor(red: 1, green: 0.992, blue: 0.968, alpha: 1)
        webView = view

        let win = NSWindow(
            contentRect: NSRect(origin: .zero, size: size),
            styleMask: [.titled, .closable],
            backing: .buffered,
            defer: false
        )
        win.title = title
        win.isReleasedWhenClosed = false
        win.backgroundColor = .white
        win.appearance = NSAppearance(named: .aqua)
        win.contentView = view
        win.center()

        // onboarding: seamless chrome — the web header IS the top bar, with
        // the traffic lights floating over the cream page (web side pads
        // its header to clear them)
        if route == .onboarding {
            win.styleMask.insert(.fullSizeContentView)
            win.titlebarAppearsTransparent = true
            win.titleVisibility = .hidden
            win.isMovableByWindowBackground = true
        }

        window = win

        super.init()

        bridge.onMessage = { [weak self] body in
            self?.handleMessage(body)
        }

        win.delegate = self
        view.navigationDelegate = self

        loadPage()
        observeStores()
        startPermissionPolling()
    }

    func present() {
        NSApp.activate(ignoringOtherApps: true)
        window.makeKeyAndOrderFront(nil)
        pushState()
    }

    /// Menu-driven pane switching on an already-open window.
    func showPane(_ pane: String) {
        guard pageReady else {
            pendingPane = pane
            return
        }
        webView.evaluateJavaScript("window.__typie.setPane && window.__typie.setPane('\(pane)')")
    }

    func setOnboardingStep(_ step: Int) {
        let clamped = max(0, min(step, 3))
        webView.evaluateJavaScript("window.__typie?.setStep && window.__typie.setStep(\(clamped))")
    }

    func setOnboardingRecheck(_ active: Bool) {
        webView.evaluateJavaScript("window.__typie?.setRecheck && window.__typie.setRecheck(\(active ? "true" : "false"))")
    }

    func close() {
        window.close()
    }

    // MARK: page load

    /// Root of the bundled web UI (WebResources/webui/, copied verbatim
    /// by SPM's .copy rule). Served to the WebView over a custom scheme —
    /// file:// URLs can't fetch ES modules (CORS), so we speak "typie://".
    static let webUIRoot: URL? = {
        let bundle = Bundle.typieResources
        let indexURL = bundle?.url(forResource: "index", withExtension: "html", subdirectory: "WebResources/webui")
            ?? bundle?.url(forResource: "index", withExtension: "html", subdirectory: "webui")
            ?? bundle?.url(forResource: "index", withExtension: "html")
        return indexURL?.deletingLastPathComponent()
    }()

    private func loadPage() {
        guard Self.webUIRoot != nil else {
            AppLog.event("webui: index.html NOT FOUND in resource bundle — window will be blank")
            return
        }
        webView.load(URLRequest(url: URL(string: "typie://webui/index.html")!))
    }

    // MARK: state observation

    private func observeStores() {
        SettingsStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        StatsStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        HistoryStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        ModelManager.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        DiarizeStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        NoteStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        TranscriptStore.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        MeetingAIService.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        DictationController.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
        MeetingController.shared.objectWillChange
            .sink { [weak self] _ in self?.schedulePush() }
            .store(in: &cancellables)
    }

    /// Permissions don't publish — poll while the window exists so the
    /// onboarding badges flip the moment the user approves in System Settings.
    /// Poll every 2s (was 0.7s — caused jank) and only pushes if permissions changed.
    private var lastPermissionSnapshot: String = ""
    private func startPermissionPolling() {
        permissionPoller = Timer.scheduledTimer(withTimeInterval: 2.0, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self else { return }
                let snap = "\(AudioCapture.micPermissionGranted())-\(HotkeyMonitor.accessibilityGranted(prompt: false))-\(SystemAudioRecorder.permissionGranted())"
                if snap != self.lastPermissionSnapshot {
                    self.lastPermissionSnapshot = snap
                    self.pushState()
                }
            }
        }
    }

    private func schedulePush() {
        // coalesce bursts (diarize progress ticks fire many times a second,
        // and each push serializes the whole library) — at most ~8 pushes/sec
        guard !pushPending else { return }
        pushPending = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) { [weak self] in
            self?.pushPending = false
            self?.pushState()
        }
    }

    private var pushPending = false

