        script = script
            .replacingOccurrences(of: "\u{2028}", with: "\\u2028")
            .replacingOccurrences(of: "\u{2029}", with: "\\u2029")

        webView.evaluateJavaScript("window.__typie && __typie.push(\(script))")
    }

    /// Local-footprint numbers for the sidebar's privacy meter: everything
    /// typie keeps (models + notes + transcripts + history) vs. the disk.
    /// Cached for 10s to avoid enumerating on every push (was causing jank).
    private static var cachedStorage: (dict: [String:Any], at: Date)?
    private static func storageDict() -> [String: Any] {
        if let c = cachedStorage, Date().timeIntervalSince(c.at) < 10 { return c.dict }
        let used = dirSize(AppPaths.supportDir) + dirSize(AppPaths.modelsRoot)
        let free = (try? FileManager.default.attributesOfFileSystem(forPath: "/")[.systemFreeSize] as? Int64) ?? 0
        let total = (try? FileManager.default.attributesOfFileSystem(forPath: "/")[.systemSize] as? Int64) ?? 0
        let dict: [String:Any] = ["usedBytes": used, "freeBytes": Int(free), "totalBytes": Int(total)]
        cachedStorage = (dict, Date())
        return dict
    }

    private static func dirSize(_ url: URL) -> Int {
        // skip hidden and package contents for speed
        guard let enumerator = FileManager.default.enumerator(
            at: url, includingPropertiesForKeys: [.fileSizeKey, .isRegularFileKey], options: [.skipsHiddenFiles])
        else { return 0 }
        var total = 0
        for case let fileURL as URL in enumerator {
            let vals = try? fileURL.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey])
            if vals?.isRegularFile == true { total += vals?.fileSize ?? 0 }
            // cap early to keep UI snappy on huge libraries
            if total > 50*1024*1024*1024 { break }
        }
        return total
    }

    private func modelStatusDict() -> [String: Any] {
        switch ModelManager.shared.status {
        case .notDownloaded:
            return ["status": "notDownloaded", "fraction": 0.0, "error": ""]
        case .downloading(let fraction):
            return ["status": "downloading", "fraction": fraction, "error": ""]
        case .loading:
            return ["status": "loading", "fraction": 0.98, "error": ""]
        case .ready:
            return ["status": "ready", "fraction": 1.0, "error": ""]
        case .failed(let message):
            return ["status": "failed", "fraction": 0.0, "error": message]
        }
    }

