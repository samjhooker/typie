                // METADATA ONLY — turns/words made every push O(library) on
                // the main thread and froze the whole UI during processing.
                // The detail pane fetches one full transcript via "transcriptGet".
                [
                    "id": transcript.id.uuidString,
                    "fileName": transcript.fileName,
                    "date": Self.iso8601.string(from: transcript.date),
                    "durationSeconds": transcript.durationSeconds,
                    "speakerCount": transcript.speakerCount,
                    "elapsedMs": transcript.elapsedMs,
                    "isMeeting": transcript.isMeeting,
                    "hasAudio": transcript.audioFile != nil,
                    "audioUrl": transcript.audioFile.map { "transcript-audio/\($0)" } ?? "",
                    "turnCount": transcript.turns.count,
                    "preview": (transcript.aiSummary ?? String(transcript.turns.first?.text.prefix(120) ?? "")),
                    "speakerNames": Dictionary(uniqueKeysWithValues: transcript.speakerNames.map { (String($0.key), $0.value) }),
                    "aiTitle": transcript.aiTitle ?? "",
                    "aiSummary": transcript.aiSummary ?? "",
                    "aiStatus": transcript.aiStatus ?? "",
                    "aiEngine": transcript.aiEngine ?? "",
                    "aiTopics": (transcript.aiTopics ?? []).map { t in ["title": t.title, "start": t.startSeconds, "summary": t.summary] as [String: Any] },
                    "aiSections": (transcript.aiSections ?? []).map { s in ["title": s.title, "start": s.startSeconds, "ts": s.timestampLabel, "points": s.points.map { p in ["text": p.text, "start": p.startSeconds] as [String: Any] }] as [String: Any] },
                    "aiQuotes": (transcript.aiQuotes ?? []).map { q in ["text": q.text, "speaker": q.speaker, "start": q.startSeconds, "ts": q.timestampLabel] as [String: Any] },
                    "aiActions": (transcript.aiActions ?? []).map { a in ["speaker": a.speaker, "text": a.text, "start": a.startSeconds, "ts": a.timestampLabel] as [String: Any] },
                    "aiProgress": transcript.aiProgress ?? -1,
                ] as [String: Any]
            },
            "aiAvailable": MeetingAIService.shared.isSupported,
            "dictation": [
                "phase": phaseString(controller.phase),
                "lastMs": phaseMs(controller.phase),
                "transcript": controller.lastTranscript ?? "",
            ],
            "capturingHotkey": capturingHotkey,
            "eta": etaText(),
