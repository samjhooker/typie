    private func transcribeStateDict() -> [String: Any] {
        let store = DiarizeStore.shared
        store.refreshModelState()

        let model: [String: Any]
        switch store.modelState {
        case .unknown:
            model = ["state": "unknown", "fraction": 0.0, "error": ""]
        case .notDownloaded:
            model = ["state": "notDownloaded", "fraction": 0.0, "error": ""]
        case .downloading(let fraction):
            model = ["state": "downloading", "fraction": fraction, "error": ""]
        case .compiling:
            model = ["state": "compiling", "fraction": 1.0, "error": ""]
        case .ready:
            model = ["state": "ready", "fraction": 1.0, "error": ""]
        case .failed(let message):
            model = ["state": "failed", "fraction": 0.0, "error": message]
        }

        var dict: [String: Any] = [
            "model": model,
            "downloadMB": DiarizeStore.downloadSizeMB,
            "busy": store.busy,
            "stage": store.stage,
            "progress": store.progress.map(NSNumber.init(value:)) ?? NSNull(),
            "eta": store.etaText,
            "queued": DiarizeStore.shared.queuedCount,
            "queue": DiarizeStore.shared.queueDict,
            "error": store.errorText ?? "",
        ]

        if let r = store.result {
            dict["result"] = [
                "fileName": r.fileName,
                "durationSeconds": r.durationSeconds,
                "speakerCount": r.speakerCount,
                "elapsedMs": r.elapsedMs,
                "plainTranscript": r.plainTranscript,
                "turns": r.turns.map { turn in
                    [
                        "speaker": turn.speakerIndex,
                        "start": turn.startSeconds,
                        "end": turn.endSeconds,
                        "text": turn.text,
                    ] as [String: Any]
                },
            ] as [String: Any]
        }
        return dict
    }

    private func presentAudioOpenPanel() {
        // no busy guard — extra picks just line up in the queue
        let panel = NSOpenPanel()
        panel.canChooseDirectories = false
        panel.allowsMultipleSelection = true
        panel.allowedContentTypes = [.audio, .movie]
        panel.message = "choose audio to transcribe with speaker labels"
        panel.beginSheetModal(for: window) { [weak self] response in
            guard response == .OK else { return }
            for url in panel.urls {
                DiarizeStore.shared.submit(url: url, isMeeting: false, owned: false)
            }
            _ = self // controller keeps the sheet's parent window alive
        }
    }

    /// Drag-and-drop arrives as a chunked base64 upload (WKWebView gives JS
    /// File objects without paths), which we reassemble into a temp file.
    /// Stage a completed chunk-upload into typie's own data dir (a persistent
    /// staging copy — NOT tmp), then enqueue it. The store adopts the staged
    /// file by move, so every transcript keeps its own unique audio copy.
    private func finishDrop(_ upload: DropUpload) {
        let ext = (upload.name as NSString).pathExtension
        let safeExt = ext.isEmpty ? "wav" : ext
        let displayName = upload.name
        let stagedURL = TranscriptStore.uploadsDir
            .appendingPathComponent("\(UUID().uuidString).\(safeExt)")
        // uploads can be hundreds of MB — stage the file off the main thread
        Task.detached(priority: .userInitiated) { [weak self] in
            do {
                try upload.data.write(to: stagedURL)
            } catch {
                AppLog.event("transcribe: failed to stage dropped file — \(error.localizedDescription)")
                return
            }
            await MainActor.run { [weak self] in
                self?.enqueueTranscribe(url: stagedURL, name: displayName)
            }
        }
    }

    private func enqueueTranscribe(url: URL, name: String) {
        DiarizeStore.shared.submit(url: url, isMeeting: false, owned: true, displayName: name)
    }

    // MARK: transcribe job queue (multiple uploads processed back-to-back)
    // the queue itself lives in DiarizeStore so meetings + uploads share it

    private static func uuid(from body: [String: Any]) -> UUID? {
        (body["id"] as? String).flatMap(UUID.init(uuidString:))
    }

    private func phaseString(_ phase: DictationPhase) -> String {
        switch phase {
        case .idle: return "idle"
        case .listening: return "listening"
        case .transcribing: return "transcribing"
        case .done: return "done"
        }
    }

    private func phaseMs(_ phase: DictationPhase) -> Double {
        if case .done(let ms) = phase { return ms }
        return -1
    }

    /// Rough ETA from observed download rate so far.
    private func etaText() -> String {
        guard let start = Self.downloadStart else { return "" }
        let elapsed = -start.timeIntervalSinceNow
        let fraction = ModelManager.shared.progressFraction
        guard elapsed > 3, fraction > 0.03, fraction < 1 else { return "" }
        let remaining = elapsed / fraction * (1 - fraction)
        if remaining >= 90 {
            return String(format: "about %d min left", Int((remaining / 60).rounded()))
        } else {
            return String(format: "about %d sec left", max(5, Int((remaining / 10).rounded() * 10)))
        }
    }

    // MARK: hotkey capture

    private func startHotkeyCapture() {
        guard captureMonitor == nil else { return }
        capturingHotkey = true
        pushState()
        captureMonitor = NSEvent.addLocalMonitorForEvents(matching: [.flagsChanged, .keyDown]) {
            [weak self] event in
            MainActor.assumeIsolated {
                guard let self else { return event }
                return self.handleCaptureEvent(event)
            }
        }
    }

    private func handleCaptureEvent(_ event: NSEvent) -> NSEvent? {
        switch event.type {
        case .flagsChanged:
            if let key = HotkeyKey.fromKeyCode(Int(event.keyCode)) {
                SettingsStore.shared.hotkey = key
                stopHotkeyCapture()
                return nil // swallow the modifier so it doesn't trigger menus/dictation
            }
            return event
        case .keyDown:
            if Int(event.keyCode) == 53 { // esc cancels
                stopHotkeyCapture()
                return nil
            }
            return event
        default:
            return event
        }
    }

    private func stopHotkeyCapture() {
        capturingHotkey = false
        if let monitor = captureMonitor {
            NSEvent.removeMonitor(monitor)
        }
        captureMonitor = nil
        pushState()
    }

    // MARK: teardown

    private func tearDown() {
        permissionPoller?.invalidate()
        permissionPoller = nil
        if let monitor = captureMonitor {
            NSEvent.removeMonitor(monitor)
            captureMonitor = nil
        }
        capturingHotkey = false
        webView.configuration.userContentController.removeScriptMessageHandler(forName: "typie")
        cancellables.removeAll()
    }

    deinit {
        // timers/monitors are torn down in windowWillClose(_:); nothing
        // main-actor-isolated happens here
    }

    // MARK: NSWindowDelegate forwarding

    nonisolated func windowWillClose(_ notification: Notification) {
        Task { @MainActor [weak self] in
            guard let self else { return }
            self.tearDown()
            self.onWillClose?()
        }
    }

    nonisolated func windowDidBecomeKey(_ notification: Notification) {
        Task { @MainActor [weak self] in self?.onBecomeKey?() }
    }

    nonisolated func windowDidResignKey(_ notification: Notification) {
        Task { @MainActor [weak self] in self?.onResignKey?() }
    }
}

// MARK: - JS -> Swift actions

extension WebUIController: WKNavigationDelegate {
    private func handleMessage(_ body: [String: Any]) {
        let type = body["type"] as? String ?? ""

        switch type {
        case "ready":
            pageReady = true
            AppLog.event("webui: page ready (\(route.rawValue))")
            if let pane = pendingPane {
                pendingPane = nil
                showPane(pane)
            }
            pushState()

        case "requestMicPermission":
            AudioCapture.requestMicPermission { [weak self] _ in
                self?.pushState()
            }

        case "requestAccessibility":
            _ = HotkeyMonitor.accessibilityGranted(prompt: true)

        case "requestScreenPermission":
            SystemAudioRecorder.requestPermission()
            // give meeting controller a chance to start after permission granted
            DispatchQueue.main.asyncAfter(deadline: .now()+0.6) { [weak self] in self?.pushState() }

        case "toggleNoteRecording":
            NoteStore.shared.toggleRecord()

        case "toggleMeetingRecording":
            MeetingController.shared.toggle()

        case "revealStorage":
            // the button in the sidebar footer: show the data folder in Finder
            NSWorkspace.shared.open(AppPaths.supportDir)

        case "startModelDownload":
            if !ModelManager.modelsExist() { Self.downloadStart = Date() }
            Task { await ModelManager.shared.downloadAndLoad() }

        case "startDiarizerDownload":
            Task { await DiarizeStore.shared.downloadAndLoad() }

        case "transcribeChooseFile":
            presentAudioOpenPanel()

        case "transcribeDropBegin":
            guard let name = body["name"] as? String,
                body["totalChunks"] != nil
            else { return }
            dropUpload = DropUpload(name: name)

        case "transcribeDropChunk":
            guard dropUpload != nil, body["index"] != nil,
                let b64 = body["b64"] as? String,
                let chunk = Data(base64Encoded: b64)
            else { return }
            dropUpload?.data.append(chunk)

        case "transcribeDropEnd":
            guard let upload = dropUpload else { return }
            dropUpload = nil
            guard !upload.data.isEmpty else { return }
            finishDrop(upload)

        case "setSetting":
            applySetting(key: body["key"] as? String, value: body["value"])

        case "startHotkeyCapture":
            startHotkeyCapture()

        case "completeOnboarding":
            onComplete?()

        case "onboardingReadyStep":
            DictationController.shared.startMonitoring()

        case "copy":
            if let text = body["text"] as? String {
                NSPasteboard.general.clearContents()
                NSPasteboard.general.setString(text, forType: .string)
            }

        case "notesTogglePin":
            if let id = Self.uuid(from: body) { NoteStore.shared.togglePin(id) }

        case "notesDelete":
            if let id = Self.uuid(from: body) { NoteStore.shared.delete(id) }

        case "noteExport":
            if let id = Self.uuid(from: body) {
                NoteStore.shared.export(id, format: body["format"] as? String ?? "md")
            }

        case "transcriptsDelete":
            if let id = Self.uuid(from: body) { TranscriptStore.shared.delete(id) }

        case "historyDelete":
            if let id = Self.uuid(from: body) { HistoryStore.shared.remove(id) }

        case "historyClear":
            HistoryStore.shared.clear()

        case "transcriptsRename":
            if let id = Self.uuid(from: body), let name = body["name"] as? String {
                TranscriptStore.shared.rename(id, name: name)
            }

        case "transcriptsRenameSpeaker":
            if let id = Self.uuid(from: body),
               let index = body["index"] as? Int,
               let name = body["name"] as? String {
                TranscriptStore.shared.renameSpeaker(id, index: index, name: name)
            }

        case "transcriptExport":
            if let id = Self.uuid(from: body) {
                TranscriptStore.shared.export(id, format: body["format"] as? String ?? "md")
            }

        case "transcriptGet":
            // full transcript (turns + word timings) for the open detail pane
            if let id = Self.uuid(from: body),
               let t = TranscriptStore.shared.transcripts.first(where: { $0.id == id }) {
                let payload: [String: Any] = [
                    "id": id.uuidString,
                    "fileName": t.fileName,
                    "date": Self.iso8601.string(from: t.date),
                    "durationSeconds": t.durationSeconds,
                    "speakerCount": t.speakerCount,
                    "isMeeting": t.isMeeting,
                    "hasAudio": t.audioFile != nil,
                    "audioUrl": t.audioFile.map { "transcript-audio/\($0)" } ?? "",
                    "speakerNames": Dictionary(uniqueKeysWithValues: t.speakerNames.map { (String($0.key), $0.value) }),
                    "aiTitle": t.aiTitle ?? "",
                    "aiSummary": t.aiSummary ?? "",
                    "aiStatus": t.aiStatus ?? "",
                    "aiEngine": t.aiEngine ?? "",
                    "aiGeneratedAt": t.aiGeneratedAt.map { Self.iso8601.string(from: $0) } ?? "",
                    "aiTopics": (t.aiTopics ?? []).map { topic in ["title": topic.title, "start": topic.startSeconds, "summary": topic.summary] as [String: Any] },
                    "aiSections": (t.aiSections ?? []).map { s in ["title": s.title, "start": s.startSeconds, "ts": s.timestampLabel, "points": s.points.map { p in ["text": p.text, "start": p.startSeconds] as [String: Any] }] as [String: Any] },
                    "aiQuotes": (t.aiQuotes ?? []).map { q in ["text": q.text, "speaker": q.speaker, "start": q.startSeconds, "ts": q.timestampLabel] as [String: Any] },
                    "aiActions": (t.aiActions ?? []).map { a in ["speaker": a.speaker, "text": a.text, "start": a.startSeconds, "ts": a.timestampLabel] as [String: Any] },
                    "aiProgress": t.aiProgress ?? -1,
                    "turns": t.turns.map { turn in
                        [
                            "speaker": turn.speakerIndex,
                            "start": turn.startSeconds,
                            "end": turn.endSeconds,
                            "text": turn.text,
                            "words": (turn.words ?? []).map { w in
                                ["text": w.text, "start": w.start, "end": w.end]
                            },
                        ] as [String: Any]
                    },
                ]
                // stale heuristic summary + the real model now available →
                // quietly regenerate so opening an old transcript upgrades it
                if t.aiEngine == "heuristic", t.aiStatus == "done",
                   MeetingAIService.shared.isSupported {
                    AppLog.event("ai: upgrading heuristic summary to FoundationModels — \(t.fileName)")
                    Task { await TranscriptStore.shared.generateAI(for: id) }
                }
                if let data = try? JSONSerialization.data(withJSONObject: payload),
                   var json = String(data: data, encoding: .utf8) {
                    json = json.replacingOccurrences(of: "\u{2028}", with: "\\u2028")
                        .replacingOccurrences(of: "\u{2029}", with: "\\u2029")
                    webView.evaluateJavaScript("window.__typie.setTranscript && window.__typie.setTranscript(\(json))")
                }
            }

        case "transcriptGenerateAI":
            // explicit user action — heuristics allowed when the real model
            // is unavailable, because they asked for it
            if let id = Self.uuid(from: body) {
                Task { await TranscriptStore.shared.generateAI(for: id, allowHeuristic: true) }
            }

        case "transcriptClearAI":
            if let id = Self.uuid(from: body) {
                TranscriptStore.shared.clearAI(for: id)
            }

        case "log":
            AppLog.event("webui js: \(body["message"] as? String ?? "?")")

        default:
            AppLog.event("webui: unknown message type '\(type)'")
        }
    }

    private func applySetting(key: String?, value: Any?) {
        let settings = SettingsStore.shared
        switch key {
        case "triggerMode":
            if let raw = value as? String, let mode = TriggerModeBridge(rawValue: raw) {
                settings.triggerMode = mode.native
            }
        case "historyEnabled":
            if let bool = value as? Bool { settings.historyEnabled = bool }
        case "launchAtLogin":
            if let bool = value as? Bool { settings.launchAtLogin = bool }
        case "notesKeepAudio":
            if let bool = value as? Bool { settings.notesKeepAudio = bool }
        case "meetingMixMic":
            if let bool = value as? Bool { settings.meetingMixMic = bool }
        case "transcriptsKeepAudio":
            if let bool = value as? Bool { settings.transcriptsKeepAudio = bool }
        default:
            AppLog.event("webui: unknown setting '\(key ?? "")'")
        }
    }

    // MARK: navigation policy (open external links outside the app)

    nonisolated func webView(
        _ webView: WKWebView,
        decidePolicyFor navigationAction: WKNavigationAction,
        decisionHandler: @escaping (WKNavigationActionPolicy) -> Void
    ) {
        if let url = navigationAction.request.url,
           url.scheme == "http" || url.scheme == "https" {
            NSWorkspace.shared.open(url)
            decisionHandler(.cancel)
            return
        }
        decisionHandler(.allow)
    }
}

// MARK: - bridge-safe enums

/// Lowercase ids shared with the JS side (TriggerPicker.svelte).
enum TriggerModeBridge: String {
    case both
    case hold
    case toggle

    var native: TriggerMode {
        switch self {
        case .both: return .both
        case .hold: return .hold
        case .toggle: return .toggle
        }
    }
}

extension TriggerMode {
    var bridgeID: String {
        switch self {
        case .both: return "both"
        case .hold: return "hold"
        case .toggle: return "toggle"
        }
    }
}
