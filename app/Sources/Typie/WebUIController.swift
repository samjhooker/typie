            },
            "notes": NoteStore.shared.notes.map { note in
                [
                    "id": note.id.uuidString,
                    "text": note.text,
                    "date": Self.iso8601.string(from: note.date),
                    "durationSeconds": note.durationSeconds,
                    "pinned": note.pinned,
                    "hasAudio": note.audioFile != nil,
