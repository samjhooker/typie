            "history": HistoryStore.shared.entries.map { entry in
                [
                    "id": entry.id.uuidString,
                    "text": entry.text,
                    "date": Self.iso8601.string(from: entry.date),
                    "latencyMs": entry.latencyMs,
                    "hasAudio": entry.audioFile != nil,
